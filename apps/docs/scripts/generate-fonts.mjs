#!/usr/bin/env node
/**
 * Generate the self-hosted webfont assets for the docs app.
 *
 * The docs previously used `next/font/google`, which downloads from Google at
 * build/compile time. When that fetch fails Next substitutes a fallback
 * `@font-face` pointing at `local("Arial")` — silently in `next dev`, and by
 * throwing in `next build`. Self-hosting removes the build-time network
 * dependency entirely.
 *
 * Writes:
 *   public/fonts/<family>-<subset>.woff2   the font binaries
 *   app/fonts.css                          the @font-face rules
 *
 * Both are committed; this script is only needed when the font set changes.
 * Run from `apps/docs`:  node scripts/generate-fonts.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FONT_DIR = join(ROOT, "public", "fonts");
const CSS_OUT = join(ROOT, "app", "fonts.css");

// A modern UA makes Google serve woff2 rather than legacy formats.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

/** Must mirror the `next/font/google` calls this replaces. */
const FAMILIES = [
  { family: "Geist", slug: "geist", axis: "wght@100..900", preload: true },
  { family: "Geist Mono", slug: "geist-mono", axis: "wght@100..900", preload: true },
  { family: "Outfit", slug: "outfit", axis: "wght@600;700", preload: false },
];

function googleCssUrl({ family, axis }) {
  const name = family.replace(/ /g, "+");
  return `https://fonts.googleapis.com/css2?family=${name}:${axis}&display=swap`;
}

const RULE_RE = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;

async function collect(family) {
  const res = await fetch(googleCssUrl(family), { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${family.family}: Google Fonts returned ${res.status}`);
  const css = await res.text();

  const faces = [];
  let m;
  while ((m = RULE_RE.exec(css))) {
    const [, subset, body] = m;
    const pick = (prop) => (body.match(new RegExp(`${prop}\\s*:\\s*([^;]+)`)) ?? [])[1]?.trim();
    const url = (body.match(/url\((https:[^)]+)\)/) ?? [])[1];
    const weight = pick("font-weight");
    const range = pick("unicode-range");
    if (!url || !weight || !range) throw new Error(`${family.family}/${subset}: unparsable rule`);
    faces.push({
      family: family.family,
      subset,
      weight,
      range,
      url,
      style: pick("font-style") ?? "normal",
      display: pick("font-display") ?? "swap",
      file: `${family.slug}-${subset}.woff2`,
    });
  }
  if (!faces.length) throw new Error(`${family.family}: no @font-face rules found`);
  return faces;
}

const downloads = new Map(); // url -> filename
const all = [];

for (const family of FAMILIES) {
  const faces = await collect(family);
  for (const f of faces) downloads.set(f.url, f.file);
  all.push({ family, faces });
  console.log(`${family.family}: ${faces.length} face(s) — ${faces.map((f) => f.subset).join(", ")}`);
}

await mkdir(FONT_DIR, { recursive: true });
for (const [url, file] of downloads) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${file}: download failed (${res.status})`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.subarray(0, 4).toString("latin1") !== "wOF2") throw new Error(`${file}: not a woff2 file`);
  await writeFile(join(FONT_DIR, file), buf);
  console.log(`  wrote public/fonts/${file} (${buf.length} bytes)`);
}

const rule = (f) =>
  [
    "@font-face {",
    `  font-family: "${f.family}";`,
    `  font-style: ${f.style};`,
    `  font-weight: ${f.weight};`,
    `  font-display: ${f.display};`,
    `  src: url("/fonts/${f.file}") format("woff2");`,
    `  unicode-range: ${f.range};`,
    "}",
  ].join("\n");

const css = [
  "/*",
  " * Self-hosted webfonts. Generated by `scripts/generate-fonts.mjs` — do not edit by hand.",
  " *",
  " * These replace the former `next/font/google` setup, which fetched from Google at",
  " * build/compile time and silently degraded to `local(\"Arial\")` when that fetch failed.",
  " * Serving the files ourselves removes the network dependency.",
  " *",
  " * Fonts: Geist and Geist Mono (SIL OFL 1.1), Outfit (SIL OFL 1.1).",
  " * See `public/fonts/README.md` for provenance and licensing.",
  " */",
  "",
  ...all.flatMap(({ faces }) => faces.map(rule).concat("")),
]
  .join("\n")
  .replace(/\n+$/, "\n");

await writeFile(CSS_OUT, css);
console.log(`\nwrote app/fonts.css (${all.reduce((n, a) => n + a.faces.length, 0)} @font-face rules)`);
console.log(`total font files: ${downloads.size}`);
